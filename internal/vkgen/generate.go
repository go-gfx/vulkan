package vkgen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"math"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

// Config says what to generate. Names are the registry's (VkBufferCreateInfo).
type Config struct {
	Package   string
	Structs   []string // structures to mirror, and every type they reach
	Handles   []string // handles to declare even when no structure holds them
	Enums     []string // enumerations whose every enumerator becomes a constant
	Constants []string // API constants (VK_WHOLE_SIZE)
}

// Output is the generated source: the types, and a test that pins their layout.
type Output struct {
	Types      []byte
	LayoutTest []byte
}

type scalar struct {
	goType string
	size   int
}

// The C types of the registry on a 64-bit LP64 or LLP64 target. size_t is
// 8 bytes because the package is 64-bit only.
var cScalars = map[string]scalar{
	"uint8_t": {"uint8", 1}, "int8_t": {"int8", 1}, "char": {"byte", 1},
	"uint16_t": {"uint16", 2}, "int16_t": {"int16", 2},
	"uint32_t": {"uint32", 4}, "int32_t": {"int32", 4}, "int": {"int32", 4},
	"uint64_t": {"uint64", 8}, "int64_t": {"int64", 8},
	"float": {"float32", 4}, "double": {"float64", 8},
	"size_t": {"uintptr", 8},
}

type info struct {
	goName string
	size   int
	align  int
}

type field struct {
	goName string
	offset int
}

type layout struct {
	goName string
	size   int
	align  int
	fields []field
}

type generator struct {
	reg     *Registry
	infos   map[string]info
	decls   map[string]string // Go name -> declaration
	layouts []layout
	busy    map[string]bool
	stypes  map[string]bool // VkStructureType enumerators the structures need
}

// Generate emits the Go source for cfg. The output is deterministic.
func Generate(reg *Registry, cfg Config) (*Output, error) {
	if cfg.Package == "" {
		return nil, errors.New("vkgen: no package name")
	}
	g := &generator{
		reg: reg, infos: map[string]info{}, decls: map[string]string{},
		busy: map[string]bool{}, stypes: map[string]bool{},
	}
	for _, n := range cfg.Structs {
		if _, ok := g.reg.Structs[g.target(n)]; !ok {
			return nil, fmt.Errorf("vkgen: struct %s is not in the registry", n)
		}
		if _, err := g.typeInfo(n); err != nil {
			return nil, err
		}
	}
	for _, n := range cfg.Handles {
		if _, ok := reg.Handles[n]; !ok {
			return nil, fmt.Errorf("vkgen: handle %s is not in the registry", n)
		}
		g.typeInfo(n) // cannot fail: the handle exists
	}
	consts := map[string]string{} // Go name -> declaration
	add := func(name, decl string) error {
		if _, dup := consts[name]; dup {
			return fmt.Errorf("vkgen: two constants are named %s", name)
		}
		if _, dup := g.decls[name]; dup {
			return fmt.Errorf("vkgen: constant %s collides with a type", name)
		}
		consts[name] = decl
		return nil
	}
	for _, n := range cfg.Enums {
		e, ok := reg.Enums[n]
		if !ok {
			return nil, fmt.Errorf("vkgen: enumeration %s is not in the registry", n)
		}
		info, _ := g.typeInfo(n) // cannot fail: the enumeration exists
		for _, v := range e.Values {
			if err := add(constName(v.Name), enumConst(constName(v.Name), info.goName, v.Value, e.Bitmask)); err != nil {
				return nil, err
			}
		}
	}
	if len(g.stypes) > 0 {
		e, ok := reg.Enums["VkStructureType"]
		if !ok {
			return nil, errors.New("vkgen: VkStructureType is not in the registry")
		}
		info, _ := g.typeInfo("VkStructureType") // cannot fail: the enumeration exists
		seen := map[string]bool{}
		for _, v := range e.Values {
			if g.stypes[v.Name] {
				seen[v.Name] = true
				if _, dup := consts[constName(v.Name)]; dup {
					continue // VkStructureType was asked for whole
				}
				if err := add(constName(v.Name), enumConst(constName(v.Name), info.goName, v.Value, false)); err != nil {
					return nil, err
				}
			}
		}
		for n := range g.stypes {
			if !seen[n] {
				return nil, fmt.Errorf("vkgen: structure type %s is not in the registry", n)
			}
		}
	}
	for _, n := range cfg.Constants {
		c, ok := reg.Constants[n]
		if !ok {
			return nil, fmt.Errorf("vkgen: constant %s is not in the registry", n)
		}
		decl, err := apiConst(n, c)
		if err != nil {
			return nil, err
		}
		if err := add(constName(n), decl); err != nil {
			return nil, err
		}
	}

	header := "// Code generated by vkgen from the Khronos registry (VK_HEADER_VERSION " + reg.Version + "); DO NOT EDIT.\n\n"
	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n\nimport \"unsafe\"\n\nvar _ unsafe.Pointer\n\n", cfg.Package)
	for _, k := range sortedKeys(g.decls) {
		b.WriteString(g.decls[k])
		b.WriteString("\n\n")
	}
	for _, k := range sortedKeys(consts) {
		b.WriteString(consts[k])
		b.WriteString("\n")
	}
	var t bytes.Buffer
	t.WriteString(header)
	fmt.Fprintf(&t, "package %s\n\nimport (\n\t\"testing\"\n\t\"unsafe\"\n)\n\n", cfg.Package)
	t.WriteString("func TestGeneratedLayout(t *testing.T) {\n")
	sort.Slice(g.layouts, func(i, j int) bool { return g.layouts[i].goName < g.layouts[j].goName })
	for i, l := range g.layouts {
		fmt.Fprintf(&t, "\t{\n\t\tvar s%d %s\n", i, l.goName)
		fmt.Fprintf(&t, "\t\tcheckLayout(t, %q, unsafe.Sizeof(s%d), %d, unsafe.Alignof(s%d), %d, []fieldOffset{\n", l.goName, i, l.size, i, l.align)
		for _, f := range l.fields {
			fmt.Fprintf(&t, "\t\t\t{%q, unsafe.Offsetof(s%d.%s), %d},\n", f.goName, i, f.goName, f.offset)
		}
		t.WriteString("\t\t})\n\t}\n")
	}
	t.WriteString("}\n")
	out := &Output{Types: b.Bytes(), LayoutTest: t.Bytes()}
	for _, src := range []*[]byte{&out.Types, &out.LayoutTest} {
		formatted, err := format.Source(*src)
		if err != nil {
			return nil, fmt.Errorf("vkgen: generated source does not format (is %q a package name?): %w", cfg.Package, err)
		}
		*src = formatted
	}
	return out, nil
}

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// target follows an alias chain.
func (g *generator) target(name string) string {
	for range 8 {
		a, ok := g.reg.Aliases[name]
		if !ok {
			break
		}
		name = a
	}
	return name
}

func goName(c string) string {
	if strings.HasPrefix(c, "Vk") && len(c) > 2 && unicode.IsUpper(rune(c[2])) {
		return c[2:]
	}
	return c
}

// constName turns VK_BUFFER_USAGE_STORAGE_BUFFER_BIT into BufferUsageStorageBufferBit.
func constName(c string) string {
	c = strings.TrimPrefix(c, "VK_")
	var b strings.Builder
	for _, p := range strings.Split(c, "_") {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + strings.ToLower(p[1:]))
	}
	return b.String()
}

func enumConst(name, typ string, v int64, hex bool) string {
	if hex && v >= 0 {
		return fmt.Sprintf("const %s %s = %#x", name, typ, v)
	}
	return fmt.Sprintf("const %s %s = %d", name, typ, v)
}

// apiConst declares one entry of the API Constants block.
func apiConst(name string, c Constant) (string, error) {
	typ, ok := cScalars[c.Type]
	if !ok || (typ.goType != "uint32" && typ.goType != "uint64") {
		return "", fmt.Errorf("vkgen: constant %s has the unsupported type %q", name, c.Type)
	}
	v := strings.Trim(c.Value, "() ")
	var u uint64
	if rest, ok := strings.CutPrefix(v, "~"); ok {
		rest = strings.TrimSuffix(strings.TrimSuffix(rest, "ULL"), "U")
		n, err := strconv.ParseUint(rest, 10, 32)
		if err != nil {
			return "", fmt.Errorf("vkgen: constant %s: unsupported value %q", name, c.Value)
		}
		u = ^n
		if typ.size == 4 {
			u &= math.MaxUint32
		}
	} else {
		n, err := strconv.ParseUint(strings.TrimSuffix(v, "U"), 0, typ.size*8)
		if err != nil {
			return "", fmt.Errorf("vkgen: constant %s: unsupported value %q", name, c.Value)
		}
		u = n
	}
	return fmt.Sprintf("const %s %s = %#x", constName(name), typ.goType, u), nil
}

func (g *generator) typeInfo(c string) (info, error) {
	c = g.target(c)
	if i, ok := g.infos[c]; ok {
		return i, nil
	}
	if s, ok := cScalars[c]; ok {
		return info{s.goType, s.size, s.size}, nil
	}
	if g.busy[c] {
		return info{}, fmt.Errorf("vkgen: type %s contains itself", c)
	}
	g.busy[c] = true
	defer delete(g.busy, c)
	name := goName(c)
	var out info
	switch {
	case g.reg.Structs[c] != nil:
		i, err := g.structInfo(g.reg.Structs[c], name)
		if err != nil {
			return info{}, err
		}
		out = i
	case g.reg.Base[c] != "":
		s, ok := cScalars[g.reg.Base[c]]
		if !ok {
			return info{}, fmt.Errorf("vkgen: base type %s is %q, which is not a scalar", c, g.reg.Base[c])
		}
		g.decls[name] = fmt.Sprintf("type %s %s", name, s.goType)
		out = info{name, s.size, s.size}
	case g.reg.Flags[c] != "":
		base, err := g.typeInfo(g.reg.Flags[c])
		if err != nil {
			return info{}, err
		}
		s := cScalars[g.reg.Base[g.target(g.reg.Flags[c])]]
		g.decls[name] = fmt.Sprintf("type %s %s", name, s.goType)
		out = info{name, base.size, base.align}
	case g.reg.Enums[c] != nil || g.reg.EnumTypes[c]:
		under, size := "int32", 4
		if e := g.reg.Enums[c]; e != nil && e.Wide {
			under, size = "uint64", 8
		} else if e != nil && e.Bitmask {
			under = "uint32"
		}
		g.decls[name] = fmt.Sprintf("type %s %s", name, under)
		out = info{name, size, size}
	default:
		d, isHandle := g.reg.Handles[c]
		if !isHandle {
			return info{}, fmt.Errorf("vkgen: unknown type %s", c)
		}
		under := "uint64"
		if d {
			under = "uintptr"
		}
		g.decls[name] = fmt.Sprintf("type %s %s", name, under)
		out = info{name, 8, 8}
	}
	g.infos[c] = out
	return out, nil
}

func (g *generator) structInfo(s *Struct, name string) (info, error) {
	if len(s.Members) == 0 {
		return info{}, fmt.Errorf("vkgen: struct %s has no members", s.Name)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", name)
	lay := layout{goName: name, align: 1}
	off := 0
	for _, m := range s.Members {
		if m.Bits != "" {
			return info{}, fmt.Errorf("vkgen: struct %s: bit-field %s is not supported", s.Name, m.Name)
		}
		var gt string
		var size, align int
		if m.Pointer {
			gt, size, align = "unsafe.Pointer", 8, 8
		} else {
			i, err := g.typeInfo(m.Type)
			if err != nil {
				return info{}, fmt.Errorf("struct %s, member %s: %w", s.Name, m.Name, err)
			}
			gt, size, align = i.goName, i.size, i.align
		}
		count := 1
		var dims string
		for _, d := range m.Dims {
			n, err := g.dim(d)
			if err != nil {
				return info{}, fmt.Errorf("vkgen: struct %s, member %s: %w", s.Name, m.Name, err)
			}
			if n <= 0 || count > math.MaxInt32/n {
				return info{}, fmt.Errorf("vkgen: struct %s, member %s: dimension %q out of range", s.Name, m.Name, d)
			}
			count *= n
			dims += fmt.Sprintf("[%d]", n)
		}
		if m.Values != "" {
			g.stypes[m.Values] = true
		}
		off = (off + align - 1) &^ (align - 1)
		fn := strings.ToUpper(m.Name[:1]) + m.Name[1:]
		fmt.Fprintf(&b, "\t%s %s%s\n", fn, dims, gt)
		lay.fields = append(lay.fields, field{fn, off})
		off += size * count
		if align > lay.align {
			lay.align = align
		}
	}
	b.WriteString("}")
	lay.size = (off + lay.align - 1) &^ (lay.align - 1)
	g.decls[name] = b.String()
	g.layouts = append(g.layouts, lay)
	return info{name, lay.size, lay.align}, nil
}

func (g *generator) dim(d string) (int, error) {
	if n, err := strconv.Atoi(d); err == nil {
		return n, nil
	}
	c, ok := g.reg.Constants[d]
	if !ok {
		return 0, fmt.Errorf("array dimension %q is neither a number nor a constant", d)
	}
	n, err := strconv.Atoi(c.Value)
	if err != nil {
		return 0, fmt.Errorf("constant %s = %q is not a plain number", d, c.Value)
	}
	return n, nil
}
